def inside(lon, lat, poly):
    """Ray casting point-in-polygon."""
    n = len(poly)
    ok = False
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > lat) != (yj > lat):
            xint = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < xint:
                ok = not ok
        j = i
    return ok


def main():
    bits = bytearray((W * H + 7) // 8)
    land = 0
    for row in range(H):
        lat = LAT0 + (LAT1 - LAT0) * (row + 0.5) / H
        for col in range(W):
            lon = LON0 + (LON1 - LON0) * (col + 0.5) / W
            if any(inside(lon, lat, p) for p in POLYS):
                bits[(row * W + col) // 8] |= 1 << ((row * W + col) % 8)
                land += 1
    blob = base64.b64encode(bytes(bits)).decode()
    with open(os.path.join(OUT, "worldmap.txt"), "w") as f:
        f.write(blob + "\n")
    print("land cells:", land, "blob bytes:", len(blob))
    # Preview.
    from PIL import Image, ImageDraw
    img = Image.new("RGB", (W * 4, H * 4), (244, 239, 226))
    d = ImageDraw.Draw(img)
    for row in range(H):
        for col in range(W):
            if bits[(row * W + col) // 8] >> ((row * W + col) % 8) & 1:
                d.ellipse([col * 4, row * 4, col * 4 + 3, row * 4 + 3],
                          fill=(90, 90, 100))
    img.save(os.path.join(OUT, "map_preview.png"))
    print("preview saved")


